""" 
funcion bool ->  devuelven verdadero (true) o falso (false) 
"""

# 1. ejemplo numero entero y flotante
print(bool(0)) 
print(bool(0.0))
print(bool(70))

# 2. ejemplo texto (string)
print(bool(""))
print(bool(" "))
print(bool("hola"))

# 3. ejemplo None
vacio = None

print(bool(vacio))
print(bool(False))
print(bool(True))

